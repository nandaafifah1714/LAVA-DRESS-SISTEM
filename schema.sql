    'staff',
    true
  )
  ON CONFLICT (auth_user_id)
  DO UPDATE SET
    email=excluded.email,
    updated_at=now()
  RETURNING
    id,
    lower(role),
    is_active
  INTO
    profile_id,
    profile_role,
    profile_active;

  RETURN NEXT;
END;
$$;

