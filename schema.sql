      p_rental_id,
      rental_row.rental_code,
      detail_row.previous_status,
      next_status,
      0,
      detail_row.quantity,
      -detail_row.quantity,
      0,
      'Stok ukuran dikembalikan setelah rental dibatalkan'
    );
  END LOOP;

