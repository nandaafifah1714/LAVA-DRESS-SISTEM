      'penalty_receipts', penalty_receipts,
      'deposits_received', deposits_received,
      'capital_contributions', capital_total,
      'total_inflows', total_inflows,
      'refunds', refunds,
      'expense_payments', expense_payments_total,
      'purchase_payments', purchase_payments_total,
      'deposits_refunded', deposits_refunded,
      'total_outflows', total_outflows,
      'net_cash_flow', total_inflows - total_outflows
    )
  );
END;
