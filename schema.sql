CREATE OR REPLACE FUNCTION public.get_operational_report(
  p_from date,
  p_to date
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  rental_revenue numeric := 0;
  penalty_revenue numeric := 0;
  expense_total numeric := 0;
  rental_count bigint := 0;
  payment_total numeric := 0;
  refund_total numeric := 0;
  purchase_total numeric := 0;
  capital_total numeric := 0;
  return_count bigint := 0;
  receivable_total numeric := 0;
  supplier_payable_total numeric := 0;
  expense_payable_total numeric := 0;
  deposit_total numeric := 0;
  available_units numeric := 0;
  rental_rows jsonb := '[]'::jsonb;
  expense_rows jsonb := '[]'::jsonb;
  payable_rows jsonb := '[]'::jsonb;
  expense_categories jsonb := '[]'::jsonb;
  capital_rows jsonb := '[]'::jsonb;
BEGIN
  IF p_from IS NULL OR p_to IS NULL OR p_from > p_to THEN
    RAISE EXCEPTION 'Periode laporan tidak valid';
  END IF;

  SELECT
    coalesce(sum(coalesce(rental.total_rental, rental.total_amount, 0)), 0),
    count(*)
  INTO rental_revenue, rental_count
  FROM public.rentals rental
  WHERE rental.rental_date BETWEEN p_from AND p_to
    AND coalesce(rental.rental_status, rental.status, '') <> 'Cancelled';

  SELECT
    coalesce(sum(CASE WHEN payment.payment_type = 'REFUND' THEN 0 ELSE payment.amount END), 0),
    coalesce(sum(CASE WHEN payment.payment_type = 'REFUND' THEN payment.amount ELSE 0 END), 0)
  INTO payment_total, refund_total
  FROM public.payments payment
  WHERE payment.payment_date BETWEEN p_from AND p_to;

  SELECT coalesce(sum(penalty.amount), 0)
  INTO penalty_revenue
  FROM public.penalties penalty
  WHERE penalty.created_at >= p_from::timestamptz
    AND penalty.created_at < (p_to + 1)::timestamptz;

  SELECT coalesce(sum(expense.amount), 0)
  INTO expense_total
  FROM public.expenses expense
  WHERE expense.expense_date BETWEEN p_from AND p_to;

  SELECT coalesce(sum(purchase.total_amount), 0)
  INTO purchase_total
  FROM public.purchases purchase
  WHERE purchase.purchase_date BETWEEN p_from AND p_to;

  SELECT coalesce(sum(capital.amount), 0)
  INTO capital_total
  FROM public.capital_contributions capital
  WHERE capital.contribution_date BETWEEN p_from AND p_to
    AND capital.status = 'Posted';

  SELECT count(*)
  INTO return_count
  FROM public.returns returned
  WHERE returned.return_date BETWEEN p_from AND p_to;

  WITH paid AS (
    SELECT
      payment.rental_id,
      sum(CASE WHEN payment.payment_type = 'REFUND' THEN -payment.amount ELSE payment.amount END) AS amount
    FROM public.payments payment
    WHERE payment.payment_date <= p_to
      AND payment.payment_type IN ('DP','PELUNASAN','REFUND')
    GROUP BY payment.rental_id
  )
  SELECT coalesce(sum(greatest(coalesce(rental.total_rental, rental.total_amount, 0) - coalesce(paid.amount, 0), 0)), 0)
  INTO receivable_total
  FROM public.rentals rental
  LEFT JOIN paid ON paid.rental_id = rental.id
  WHERE rental.rental_date <= p_to
    AND coalesce(rental.rental_status, rental.status, '') <> 'Cancelled';

  WITH paid AS (
    SELECT payment.purchase_id, sum(payment.amount) AS amount
    FROM public.purchase_payments payment
    WHERE payment.payment_date <= p_to
    GROUP BY payment.purchase_id
  )
  SELECT coalesce(sum(
    CASE
      WHEN purchase.payment_status = 'Paid' THEN 0
      ELSE greatest(purchase.total_amount - coalesce(paid.amount, 0), 0)
    END
  ), 0)
  INTO supplier_payable_total
  FROM public.purchases purchase
  LEFT JOIN paid ON paid.purchase_id = purchase.id
  WHERE purchase.purchase_date <= p_to;

  WITH paid AS (
    SELECT payment.expense_id, sum(payment.amount) AS amount
    FROM public.expense_payments payment
    WHERE payment.payment_date <= p_to
    GROUP BY payment.expense_id
  )
  SELECT coalesce(sum(
    CASE
      WHEN expense.payment_status = 'Paid' THEN 0
      ELSE greatest(expense.amount - coalesce(paid.amount, 0), 0)
    END
  ), 0)
  INTO expense_payable_total
  FROM public.expenses expense
  LEFT JOIN paid ON paid.expense_id = expense.id
  WHERE expense.expense_date <= p_to;

  WITH returned_deposits AS (
    SELECT returned.rental_id, sum(coalesce(returned.deposit_used, 0) + coalesce(returned.deposit_refunded, 0)) AS amount
    FROM public.returns returned
    WHERE returned.return_date <= p_to
    GROUP BY returned.rental_id
  )
  SELECT coalesce(sum(greatest(coalesce(rental.deposit_received_amount, 0) - coalesce(returned.amount, 0), 0)), 0)
  INTO deposit_total
  FROM public.rentals rental
  LEFT JOIN returned_deposits returned ON returned.rental_id = rental.id
  WHERE rental.rental_date <= p_to
    AND coalesce(rental.rental_status, rental.status, '') NOT IN ('Cancelled','Completed','Returned');

  SELECT coalesce(sum(inventory.available_quantity), 0)
  INTO available_units
  FROM public.v_dress_inventory inventory;

  SELECT coalesce(jsonb_agg(row_to_json(report_row)::jsonb ORDER BY report_row.rental_date DESC), '[]'::jsonb)
  INTO rental_rows
  FROM (
    SELECT
      rental.rental_code,
      rental.rental_date,
      customer.name AS customer_name,
      coalesce(rental.total_rental, rental.total_amount, 0) AS amount,
      coalesce(paid.amount, 0) AS paid_amount,
      greatest(coalesce(rental.total_rental, rental.total_amount, 0) - coalesce(paid.amount, 0), 0) AS remaining_amount,
      coalesce(rental.rental_status, rental.status, '-') AS status
    FROM public.rentals rental
    LEFT JOIN public.customers customer ON customer.id = rental.customer_id
    LEFT JOIN (
      SELECT payment.rental_id,
        sum(CASE WHEN payment.payment_type = 'REFUND' THEN -payment.amount ELSE payment.amount END) AS amount
      FROM public.payments payment
      WHERE payment.payment_date <= p_to
        AND payment.payment_type IN ('DP','PELUNASAN','REFUND')
      GROUP BY payment.rental_id
    ) paid ON paid.rental_id = rental.id
    WHERE rental.rental_date BETWEEN p_from AND p_to
      AND coalesce(rental.rental_status, rental.status, '') <> 'Cancelled'
  ) report_row;

  SELECT coalesce(jsonb_agg(row_to_json(report_row)::jsonb ORDER BY report_row.expense_date DESC), '[]'::jsonb)
  INTO expense_rows
  FROM (
    SELECT
      expense.expense_code,
      expense.expense_date,
      category.category_name,
      expense.amount,
      expense.payment_status,
      expense.recipient,
      expense.description
    FROM public.expenses expense
    LEFT JOIN public.expense_categories category ON category.id = expense.category_id
    WHERE expense.expense_date BETWEEN p_from AND p_to
  ) report_row;

  SELECT coalesce(jsonb_agg(row_to_json(report_row)::jsonb ORDER BY report_row.purchase_date DESC), '[]'::jsonb)
  INTO payable_rows
  FROM (
    SELECT
      purchase.purchase_code,
      purchase.purchase_date,
      supplier.name AS supplier_name,
      purchase.total_amount,
      coalesce(paid.amount, 0) AS paid_amount,
      greatest(purchase.total_amount - coalesce(paid.amount, 0), 0) AS remaining_amount
    FROM public.purchases purchase
    LEFT JOIN public.suppliers supplier ON supplier.id = purchase.supplier_id
    LEFT JOIN (
      SELECT payment.purchase_id, sum(payment.amount) AS amount
      FROM public.purchase_payments payment
      WHERE payment.payment_date <= p_to
      GROUP BY payment.purchase_id
    ) paid ON paid.purchase_id = purchase.id
    WHERE purchase.purchase_date <= p_to
      AND purchase.payment_status <> 'Paid'
      AND purchase.total_amount > coalesce(paid.amount, 0)
  ) report_row;

  SELECT coalesce(jsonb_agg(row_to_json(report_row)::jsonb ORDER BY report_row.category_name), '[]'::jsonb)
  INTO expense_categories
  FROM (
    SELECT coalesce(category.category_name, 'Tanpa kategori') AS category_name,
      sum(expense.amount) AS amount,
      count(*) AS transaction_count
    FROM public.expenses expense
    LEFT JOIN public.expense_categories category ON category.id = expense.category_id
    WHERE expense.expense_date BETWEEN p_from AND p_to
