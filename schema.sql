CREATE OR REPLACE FUNCTION public.cancel_rental(
  p_rental_id bigint,
  p_reason text,
  p_deposit_action varchar,
  p_cancelled_at timestamptz DEFAULT now()
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  rental_row public.rentals%ROWTYPE;
  paid_amount numeric;
  detail_row record;
  next_status varchar;
