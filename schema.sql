CREATE OR REPLACE FUNCTION public.get_financial_statement_report(
  p_from date,
  p_to date
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  rental_revenue numeric := 0;
  penalty_revenue numeric := 0;
  operating_expenses numeric := 0;
  rental_receipts numeric := 0;
  penalty_receipts numeric := 0;
  refunds numeric := 0;
  expense_payments_total numeric := 0;
  purchase_payments_total numeric := 0;
  deposits_received numeric := 0;
  deposits_refunded numeric := 0;
  capital_total numeric := 0;
  total_inflows numeric := 0;
  total_outflows numeric := 0;
BEGIN
  IF p_from IS NULL OR p_to IS NULL OR p_from > p_to THEN
    RAISE EXCEPTION 'Periode laporan tidak valid';
  END IF;

  SELECT coalesce(sum(coalesce(rental.total_rental, rental.total_amount, 0)), 0)
  INTO rental_revenue
  FROM public.rentals rental
  WHERE rental.rental_date BETWEEN p_from AND p_to
    AND coalesce(rental.rental_status, rental.status, '') <> 'Cancelled';

  SELECT coalesce(sum(penalty.amount), 0)
  INTO penalty_revenue
  FROM public.penalties penalty
  WHERE penalty.created_at >= p_from::timestamptz
    AND penalty.created_at < (p_to + 1)::timestamptz;

  SELECT coalesce(sum(expense.amount), 0)
  INTO operating_expenses
  FROM public.expenses expense
  WHERE expense.expense_date BETWEEN p_from AND p_to;

  SELECT coalesce(sum(payment.amount), 0)
  INTO rental_receipts
  FROM public.payments payment
  WHERE payment.payment_date BETWEEN p_from AND p_to
    AND payment.payment_type IN ('DP', 'PELUNASAN');

  SELECT
    coalesce((
      SELECT sum(payment.amount)
      FROM public.penalty_payments payment
      WHERE payment.payment_date BETWEEN p_from AND p_to
    ), 0)
    + coalesce((
      SELECT sum(payment.amount)
      FROM public.payments payment
      WHERE payment.payment_date BETWEEN p_from AND p_to
        AND payment.payment_type = 'DENDA'
    ), 0)
  INTO penalty_receipts;

  SELECT coalesce(sum(payment.amount), 0)
  INTO refunds
  FROM public.payments payment
  WHERE payment.payment_date BETWEEN p_from AND p_to
    AND payment.payment_type = 'REFUND';

  SELECT
    coalesce((
      SELECT sum(payment.amount)
      FROM public.expense_payments payment
      WHERE payment.payment_date BETWEEN p_from AND p_to
    ), 0)
    + coalesce((
      SELECT sum(expense.amount)
      FROM public.expenses expense
      WHERE expense.expense_date BETWEEN p_from AND p_to
        AND expense.payment_status = 'Paid'
        AND NOT EXISTS (
          SELECT 1
          FROM public.expense_payments payment
          WHERE payment.expense_id = expense.id
        )
    ), 0)
  INTO expense_payments_total;

  SELECT
    coalesce((
      SELECT sum(payment.amount)
      FROM public.purchase_payments payment
      WHERE payment.payment_date BETWEEN p_from AND p_to
    ), 0)
    + coalesce((
      SELECT sum(purchase.total_amount)
      FROM public.purchases purchase
      WHERE purchase.purchase_date BETWEEN p_from AND p_to
        AND purchase.payment_status = 'Paid'
        AND NOT EXISTS (
          SELECT 1
          FROM public.purchase_payments payment
          WHERE payment.purchase_id = purchase.id
        )
    ), 0)
  INTO purchase_payments_total;

  SELECT coalesce(sum(rental.deposit_received_amount), 0)
  INTO deposits_received
  FROM public.rentals rental
  WHERE rental.rental_date BETWEEN p_from AND p_to;

  SELECT coalesce(sum(returned.deposit_refunded), 0)
  INTO deposits_refunded
  FROM public.returns returned
  WHERE returned.return_date BETWEEN p_from AND p_to;

  SELECT coalesce(sum(capital.amount), 0)
  INTO capital_total
  FROM public.capital_contributions capital
  WHERE capital.contribution_date BETWEEN p_from AND p_to
    AND capital.status = 'Posted'
    AND capital.contribution_type IN ('Cash', 'Bank Transfer');

  total_inflows := rental_receipts
    + penalty_receipts
    + deposits_received
    + capital_total;
  total_outflows := refunds
    + expense_payments_total
    + purchase_payments_total
    + deposits_refunded;

  RETURN jsonb_build_object(
    'from', p_from,
    'to', p_to,
    'income_statement', jsonb_build_object(
      'rental_revenue', rental_revenue,
      'penalty_revenue', penalty_revenue,
