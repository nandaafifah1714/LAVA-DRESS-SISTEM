-- can read; writes are role-gated, and accounting records are not deletable.

DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'customers',
    'suppliers',
    'dress_categories',
    'expense_categories',
    'accounts',
    'rentals',
    'rental_details',
    'payments',
    'returns',
    'penalties',
    'purchases',
    'purchase_details',
    'expenses',
    'journal_entries',
    'journal_details',
    'purchase_payments',
    'expense_payments',
    'penalty_payments'
  ]
  LOOP
    EXECUTE format(
      'ALTER TABLE %I ENABLE ROW LEVEL SECURITY',
      table_name
    );

    IF NOT EXISTS (
      SELECT 1
      FROM pg_policies
      WHERE schemaname = 'public'
        AND tablename = table_name
        AND policyname = 'authenticated_read'
    ) THEN
      EXECUTE format(
        'CREATE POLICY authenticated_read ON %I FOR SELECT TO authenticated USING (true)',
        table_name
      );
    END IF;

    IF table_name NOT IN ('accounts','journal_entries','journal_details')
      AND NOT EXISTS (
        SELECT 1
        FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = table_name
          AND policyname = 'operational_insert'
      )
    THEN
      EXECUTE format(
        'CREATE POLICY operational_insert ON %I FOR INSERT TO authenticated WITH CHECK (current_app_role() IN (''admin'',''staff'',''accounting''))',
        table_name
      );
    END IF;

    IF NOT EXISTS (
      SELECT 1
      FROM pg_policies
      WHERE schemaname = 'public'
        AND tablename = table_name
        AND policyname = 'operational_update'
    ) THEN
      EXECUTE format(
        'CREATE POLICY operational_update ON %I FOR UPDATE TO authenticated USING (current_app_role() IN (''admin'',''staff'',''accounting'')) WITH CHECK (current_app_role() IN (''admin'',''staff'',''accounting''))',
        table_name
      );
    END IF;

    IF NOT EXISTS (
      SELECT 1
      FROM pg_policies
      WHERE schemaname = 'public'
        AND tablename = table_name
        AND policyname = 'admin_delete'
    ) THEN
      EXECUTE format(
        'CREATE POLICY admin_delete ON %I FOR DELETE TO authenticated USING (current_app_role() = ''admin'')',
        table_name
      );
    END IF;
