      WHEN p_condition = 'Rusak Ringan' THEN 'Repair'
      ELSE 'Not Available'
    END;

    UPDATE public.dress_units
    SET status = next_unit_status,
        condition = next_unit_condition,
        notes = coalesce(nullif(trim(p_notes), ''), notes),
